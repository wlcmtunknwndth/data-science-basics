# 5. Создание матриц циклической структуры

# Обобщенные функции для создания циклических матриц
create_cyclic_matrix_a <- function(n) {
  outer(0:(n-1), 0:(n-1), FUN = function(x, y) (x + y) %% n)
}

create_cyclic_matrix_b <- function(n) {
  outer(0:(n-1), 0:(n-1), FUN = function(x, y) (x + y) %% n)
}

create_cyclic_matrix_c <- function(n) {
  outer(0:(n-1), 0:(n-1), FUN = function(x, y) (x - y + n) %% n)
}

# Создание всех матриц
A <- create_cyclic_matrix_a(5)
B <- create_cyclic_matrix_b(10) 
C <- create_cyclic_matrix_c(9)

print("(a) Матрица 5x5:")
print(A)

print("(b) Матрица 10x10:")
print(B)

print("(c) Матрица 9x9:")
print(C)

