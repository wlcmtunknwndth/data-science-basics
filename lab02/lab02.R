# 7. Создание матрицы и анализ данных

# Фиксируем seed для воспроизводимости
set.seed(75)

# Создаем матрицу M размерности 6x10
M <- matrix(sample(1:10, 6*10, replace = TRUE), nrow = 6, ncol = 10)

print("Матрица M:")
print(M)

# (a) Число элементов в каждой строке, которые больше 4
count_gt_4 <- apply(M, 1, function(row) sum(row > 4))
print("(a) Число элементов > 4 в каждой строке:")
print(count_gt_4)

# (b) Строки, где число 7 встречается ровно 2 раза
rows_with_two_7s <- which(apply(M, 1, function(row) sum(row == 7)) == 2)
print("(b) Строки, где число 7 встречается ровно 2 раза:")
print(rows_with_two_7s)

# (c) Пары столбцов с суммой элементов > 75
column_sums <- colSums(M)
print("Суммы по столбцам:")
print(column_sums)

# Находим все пары столбцов
pairs <- c()
for (i in 1:10) {
  for (j in 1:10) {
    if (column_sums[i] + column_sums[j] > 75) {
      pairs <- rbind(pairs, c(i, j))
    }
  }
}

print(pairs)

# Преобразуем в матрицу
if (length(pairs) > 0) {
  pairs_matrix <- matrix(pairs, ncol = 2, byrow = FALSE)
  colnames(pairs_matrix) <- c("Столбец1", "Столбец2")
  print("(c) Все пары столбцов с суммой > 75 (с повторами):")
  print(pairs_matrix)
  
  # Убираем повторы (пары, где порядок не важен)
  unique_pairs <- unique(t(apply(pairs_matrix, 1, function(x) sort(x))))
  unique_pairs_matrix <- matrix(unique_pairs, ncol = 2)
  colnames(unique_pairs_matrix) <- c("Столбец1", "Столбец2")
  print("(c) Уникальные пары столбцов с суммой > 75 (без повторов):")
  print(unique_pairs_matrix)
} else {
  print("(c) Нет пар столбцов с суммой > 75")
}

