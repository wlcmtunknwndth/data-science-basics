# Количество слагаемых после первого (последняя дробь 38/39, значит k=19)
n <- 19

# Вектор для хранения слагаемых
terms <- numeric(n + 1)
terms[1] <- 1  # первое слагаемое — 1

prod_term <- 1
for (k in 1:n) {
  prod_term <- prod_term * (2*k)/(2*k+1)
  terms[k+1] <- prod_term
}

sum_total <- sum(terms)
print(sum_total)
