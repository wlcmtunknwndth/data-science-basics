# (b) Вектор от 20 до 1
b <- 20:1  # [20, 19, ..., 1]
print(b)

# (c) Вектор от 1 до 20, а потом обратно до 1
c <- c(1:20, 19:1)  # [1, 2, ..., 20, 19, ..., 1]
print(c)

# (d) Вектор (4, 6, 3) с именем tmp
tmp <- c(4, 6, 3)
print(tmp)

# (e) Вектор (4, 6, 3) повторяется столько раз, чтобы 4 встретилась 10 раз
# 4 встречается в каждом цикле один раз, значит надо 10 циклов
e <- rep(tmp, 10)  # длина 30, 4 встретится 10 раз
print(e)

# (f) 4 встречается 11 раз, 6 и 3 по 10 раз
f <- c(rep(4, 11), rep(6, 10), rep(3, 10))  # всего 31 элемент
print(f)

# (g) 4 - 10 раз, 6 - 20 раз, 3 - 30 раз
g <- c(rep(4, 10), rep(6, 20), rep(3, 30))  # всего 60 элементов
print(g)

# (h) (2^4, 2^6, 2^3, 2^4, ..., 2^3), где 4 раза встречается 2^3
# Значит повторяем (2^4, 2^6, 2^3) 4 раза
h <- rep(c(2^4, 2^6, 2^3), 4)
print(h)
# Посчитаем, сколько раз встречается цифра 6
h_str <- paste(h, collapse = "")
count_6 <- sum(strsplit(h_str, "")[[1]] == "6")  # Считаем все '6' в строке
print(count_6)  # выводим количество шестёрок

